"""3D correlation-network graph viewer.

Two endpoints (mounted under /g/{TOKEN}/):
  GET /g/{TOKEN}/             → HTML viewer (three.js)
  GET /g/{TOKEN}/data.json    → snapshot JSON

Snapshot is generated by `python -m src.quant.correlation_snapshot` and
committed to mcp_server/api/static/graph_snapshot.json.
"""
from __future__ import annotations

import json
from pathlib import Path

from fastapi import HTTPException
from fastapi.responses import HTMLResponse, JSONResponse

_SNAPSHOT_PATH = Path(__file__).parent / "static" / "graph_snapshot.json"


def get_snapshot_json() -> JSONResponse:
    if not _SNAPSHOT_PATH.exists():
        raise HTTPException(503, "snapshot not yet generated; run src.quant.correlation_snapshot")
    return JSONResponse(content=json.loads(_SNAPSHOT_PATH.read_text()))


