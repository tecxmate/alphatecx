"""3D correlation-network graph viewer.

The viewer HTML is generated by `python -m src.quant.correlation_snapshot`
using plotly. We just serve the file. Two endpoints (mounted under
/g/{TOKEN}/):

  GET /g/{TOKEN}/             → HTML viewer
  GET /g/{TOKEN}/data.json    → snapshot JSON (for programmatic access)
"""
from __future__ import annotations

import json
from pathlib import Path

from fastapi import HTTPException
from fastapi.responses import HTMLResponse, JSONResponse

_STATIC = Path(__file__).parent / "static"
_HTML_PATH = _STATIC / "graph.html"
_JSON_PATH = _STATIC / "graph_snapshot.json"


def get_viewer_html() -> HTMLResponse:
    if not _HTML_PATH.exists():
        raise HTTPException(503, "graph.html not yet generated; "
                                 "run `python -m src.quant.correlation_snapshot`")
    return HTMLResponse(content=_HTML_PATH.read_text())


def get_snapshot_json() -> JSONResponse:
    if not _JSON_PATH.exists():
        raise HTTPException(503, "snapshot not yet generated")
    return JSONResponse(content=json.loads(_JSON_PATH.read_text()))
